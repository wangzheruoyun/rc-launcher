//! Preset renderer inventory extracted from the FCL release APK (task 9 addendum).
//!
//! `FCL-release-1.3.2.7-arm64-v8a.apk` bundles the actual OpenGL(ES)
//! translation `.so` files our built-in renderers wrap. This module snapshots
//! that inventory (file names, uncompressed sizes, SHA-256 and SHA-1) so the
//! launcher can *preset* the renderers it ships, inject the right native libs
//! and later verify (integrity) that a deployed `nativeLibraryDir` actually
//! contains the expected renderer binaries — without carrying the 172 MB APK
//! at runtime.
//!
//! The snapshot is embedded as `const` data below (generated by
//! `docs/gen_fcl_apk_manifest.py` from the APK); see [`FCL_APK_RENDERER_MANIFEST`]
//! and [`preset_registry`].

use std::path::Path;

