impl FclApkRendererManifest {
    /// The preset renderers in this APK.
    pub fn renderers(&self) -> &[FclApkRenderer] {
        self.renderers
    }

    /// Every distinct `.so` file name across all preset renderers.
    pub fn all_lib_names(&self) -> Vec<&'static str> {
        let mut out: Vec<&'static str> = Vec::new();
        for r in self.renderers {
            for l in r.libs {
                if !out.contains(&l.file_name) {
                    out.push(l.file_name);
                }
            }
        }
        out
    }

    /// Verify an on-disk native lib directory against this manifest.
    ///
    /// For each preset renderer lib present under `native_lib_dir`, checks
    /// the file size (and SHA-1 when recorded). Returns the per-lib results.
    pub fn verify_native_lib_dir(&self, native_lib_dir: &Path) -> Vec<(String, LibVerify)> {
        let mut out = Vec::new();
        for r in self.renderers {
            for l in r.libs {
                let path = native_lib_dir.join(l.file_name);
                let nl = NativeLib {
                    file_name: l.file_name.to_string(),
                    abi: None,
                    source: crate::plugins::native_lib::NativeLibSource::NativeLibDir,
                    load_order: 0,
                    optional: true,
                    expected_size: Some(l.size),
                    expected_sha256: Some(l.sha256.to_string()),
                    expected_sha1: Some(l.sha1.to_string()),
                };
                let res = match nl.verify_on_disk(&path) {
                    Ok(v) => v,
                    Err(_) => LibVerify::Missing,
                };
                out.push((format!("{}::{}", r.id, l.file_name), res));
            }
        }
        out
    }
}

/// The embedded manifest singleton.
pub fn manifest() -> &'static FclApkRendererManifest {
    &FCL_APK_RENDERER_MANIFEST
}

/// Build a [`RendererRegistry`] preset from the FCL APK inventory.
///
/// Each preset renderer carries the *actual* native libs the APK ships
/// (the primary `gl_libname` is required; dependency `.so`s are optional)
/// together with their sizes / hashes for integrity verification, and is
/// scoped to `arm64-v8a` (the only ABI this APK provides).
pub fn preset_registry() -> RendererRegistry {
    use crate::launch::options::Renderer;
    let mut reg = RendererRegistry::builtin();
    for r in manifest().renderers() {
        let base = match r.id {
            "opengles2" => Renderer::Gl4es,
            "opengles2_ng" => Renderer::NgGl4es,
            "opengles2_vgpu" => Renderer::VirGl,
            "opengles3_desktopgl_zink_kopper" => Renderer::Zink,
            "opengles3_angle" => Renderer::Angle,
            _ => continue,
        };
        let mut plugin = renderer_plugin(base);
        plugin.native_libs = r
            .libs
            .iter()
            .map(|e| {
                let mut nl = NativeLib::in_native_lib_dir(e.file_name);
                nl.expected_size = Some(e.size);
                nl.expected_sha256 = Some(e.sha256.to_string());
                nl.expected_sha1 = Some(e.sha1.to_string());
                // primary lib (the one LWJGL dlopens) is required; deps optional
                if e.file_name != plugin.gl_libname {
                    nl.optional = true;
                }
                nl
            })
            .collect();
        plugin.supported_abis = vec![Abi::Arm64V8a];
        plugin.trust = TrustLevel::System;
        reg.register(plugin);
    }
    reg
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashMap;
    use std::fs::File;
    use std::path::PathBuf;

    use zip::ZipArchive;

    use crate::plugins::renderer::RendererRegistry;

    #[test]
    fn preset_registry_has_five_with_integrity() {
        let reg = preset_registry();
        assert_eq!(reg.all().len(), 5);
        for p in reg.all() {
            assert_eq!(p.trust, TrustLevel::System);
            assert_eq!(p.supported_abis, vec![Abi::Arm64V8a]);
            assert!(!p.native_libs.is_empty());
            for nl in &p.native_libs {
                // every preset lib carries the APK integrity metadata
                assert!(nl.expected_size.is_some(), "{} missing size", nl.file_name);
                assert!(nl.expected_sha1.is_some(), "{} missing sha1", nl.file_name);
                assert!(
                    nl.expected_sha256.is_some(),
                    "{} missing sha256",
                    nl.file_name
                );
                // the primary lib (the one LWJGL dlopens) is required; deps optional
                if nl.file_name == p.gl_libname {
                    assert!(!nl.optional);
                } else {
                    assert!(nl.optional);
                }
            }
        }
    }

    #[test]
    fn manifest_primary_lib_matches_builtin_gl_libname() {
        let reg = RendererRegistry::builtin();
        for r in manifest().renderers() {
            let builtin = reg
                .get(r.id)
                .unwrap_or_else(|| panic!("manifest id `{}` must map to a built-in", r.id));
            let primary = r.libs.iter().find(|l| l.file_name == builtin.gl_libname);
            assert!(
                primary.is_some(),
                "manifest renderer `{}` must list its primary lib `{}`",
                r.id,
                builtin.gl_libname
            );
        }
    }

    #[test]
    fn manifest_lib_names_are_all_present_in_apk_layout() {
        // Every preset lib name must be a bare `lib*.so` (no surprises).
        for name in manifest().all_lib_names() {
            assert!(
                name.starts_with("lib") && name.ends_with(".so"),
                "bad lib name {name}"
            );
        }
    }

    #[test]
    fn cross_check_manifest_against_apk() {
        // Gated: only runs when the FCL release APK is available on disk. Opens
        // the APK as a zip and confirms every manifest lib (name + uncompressed
        // size) is actually present in `lib/arm64-v8a/`. This proves the preset
        // is truthful rather than hand-maintained.
        let candidate = std::env::var("FCL_APK_PATH")
            .unwrap_or_else(|_| "../../../fcl-apk/FCL-release-1.3.2.7-arm64-v8a.apk".to_string());
        let path = PathBuf::from(candidate);
        if !path.exists() {
            eprintln!("skipping cross-check: APK not found at {}", path.display());
            return;
        }
        let file = File::open(&path).expect("open FCL APK");
        let mut archive = ZipArchive::new(file).expect("read FCL APK as zip");
        let mut apk_libs: HashMap<String, u64> = HashMap::new();
        for i in 0..archive.len() {
            let e = archive.by_index(i).expect("zip entry");
            let name = e.name().to_string();
            if let Some(rest) = name.strip_prefix("lib/arm64-v8a/") {
                if name.ends_with(".so") {
                    apk_libs.insert(rest.to_string(), e.size());
                }
            }
        }
        for r in manifest().renderers() {
            for l in r.libs {
                let actual = apk_libs.get(l.file_name).unwrap_or_else(|| {
                    panic!(
                        "manifest lib {} (renderer `{}`) not found in APK",
                        l.file_name, r.id
                    )
                });
                assert_eq!(
                    *actual, l.size,
                    "uncompressed size mismatch for {} in APK",
                    l.file_name
                );
            }
        }
    }
}
