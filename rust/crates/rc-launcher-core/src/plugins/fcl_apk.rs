/// One native library the FCL APK bundles for a renderer, with integrity info.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ApkLibEntry {
    pub file_name: &'static str,
    pub size: u64,
    pub sha256: &'static str,
    pub sha1: &'static str,
}

/// A renderer preset extracted from the FCL APK (arm64-v8a).
#[derive(Debug, Clone)]
pub struct FclApkRenderer {
    pub id: &'static str,
    pub display_name: &'static str,
    pub libs: &'static [ApkLibEntry],
}

/// The embedded FCL APK renderer inventory.
